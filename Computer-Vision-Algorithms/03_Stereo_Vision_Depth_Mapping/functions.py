"""### Υπολογισμός Ορθοκανονικών Φίλτρων (orthonormalFilterBanks)
Η παρακάτω συνάρτηση δέχεται το βαθυπερατό φίλτρο ανάλυσης $h_0$ (ως `h`) μήκους $K$ και κατασκευάζει τα υπόλοιπα τρία φίλτρα της συστοιχίας: το υψιπερατό ανάλυσης $h_1$, το βαθυπερατό σύνθεσης $g_0$ και το υψιπερατό σύνθεσης $g_1$. Για να ικανοποιούνται αυστηρά οι εξισώσεις (14)-(17) της εκφώνησης (οι οποίες εισάγουν χρονικές αναστροφές $z^{-1}$ και καθυστερήσεις $z^{-2K+1}$), τα φίλτρα τοποθετούνται σε έναν κοινό, ευρύτερο άξονα χρόνου γεμισμένο με μηδενικά (zero-padding). Έτσι εξασφαλίζεται η τέλεια ευθυγράμμιση της αρχής των χρόνων ($n=0$) για το επόμενο βήμα της συνέλιξης.
"""

def orthonormalFilterBanks(h: np.ndarray):
    """
    Δημιουργεί τη συστοιχία ορθοκανονικών φίλτρων (h0, h1, g0, g1)
    βάσει των εξισώσεων (14)-(17) της εκφώνησης.
    """
    K = len(h)

    # 1. Εύρεση των ορίων του κοινού άξονα χρόνου n.
    # Το h0(n) ζει στο [0, K-1].
    # Το g0(n) = h0(-n) ζει στο [-(K-1), 0].
    # Το g1(n) λόγω της καθυστέρησης -2K+1 ζει στο [2K-1, 3K-2].
    # Το h1(n) = g1(-n) ζει στο [-(3K-2), -(2K-1)].
    n_min = -(3 * K - 2)
    n_max = 3 * K - 2
    total_length = n_max - n_min + 1

    # Αρχικοποίηση των πινάκων με μηδενικά (zero-padding)
    h0 = np.zeros(total_length)
    h1 = np.zeros(total_length)
    g0 = np.zeros(total_length)
    g1 = np.zeros(total_length)

    # Βοηθητική συνάρτηση που αντιστοιχεί τον πραγματικό χρόνο n
    # στον δείκτη του πίνακα της Python (που ξεκινάει από το 0).
    def idx(n):
        return n - n_min

    # Υπολογισμός h0(n)
    for n in range(0, K):
        h0[idx(n)] = h[n]

    # Υπολογισμός g0(n) = h0(-n) [Εξίσωση 16: H0(z) = G0(z^-1) => g0(n) = h0(-n)]
    for n in range(-(K-1), 1):
        g0[idx(n)] = h[-n]

    # Υπολογισμός g1(n) [Εξίσωση 15: G1(z) = -z^{-2K+1} G0(-z^{-1}) = -z^{-2K+1} H0(-z)]
    # Στο πεδίο του χρόνου αυτό μεταφράζεται ως: g1(n) = -(-1)^{n-2K+1} * h0(n-2K+1)
    for n in range(2*K - 1, 3*K - 1):
        g1[idx(n)] = -((-1) ** (n - 2*K + 1)) * h[n - 2*K + 1]

    # Υπολογισμός h1(n) = g1(-n) [Εξίσωση 17: H1(z) = G1(z^-1)]
    for n in range(-(3*K - 2), -(2*K - 1) + 1):
        h1[idx(n)] = g1[idx(-n)]

    return h0, h1, g0, g1

