"""### Ανάλυση 1 Διάστασης (analysis1d)
Η συνάρτηση `analysis1d` πραγματοποιεί συνέλιξη του 1Δ σήματος εισόδου με τα φίλτρα ανάλυσης (βαθυπερατό $h_0$ και υψιπερατό $h_1$). Στη συνέχεια ακολουθεί υποδειγματοληψία 1:2 (downsampling), κρατώντας δηλαδή 1 στα 2 δείγματα. Χρησιμοποιείται η παράμετρος `mode='full'` στη συνέλιξη για να διατηρηθεί όλη η πληροφορία στα άκρα, όπως απαιτείται για την τέλεια ανακατασκευή.
"""

def analysis1d(h0: np.ndarray, h1: np.ndarray, x: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """
    Υλοποιεί την 1Δ πολυδιακριτική ανάλυση (Φιλτράρισμα -> Downsampling 1:2).
    """
    # 1. Φιλτράρισμα με τα φίλτρα ανάλυσης
    # Χρησιμοποιούμε mode='full' για να μην κοπεί πληροφορία στα άκρα
    v0 = convolve(x, h0, mode='full')
    v1 = convolve(x, h1, mode='full')

    # 2. Υποδειγματοληψία 1:2 (Downsampling)
    # Κρατάμε μόνο τα άρτια δείγματα (indices 0, 2, 4, ...)
    y0 = v0[::2]
    y1 = v1[::2]

    return y0, y1

"""### Σύνθεση 1 Διάστασης (synthesis1d)
Η συνάρτηση `synthesis1d` κάνει την αντίστροφη διαδικασία: εφαρμόζει υπερδειγματοληψία 2:1 (upsampling) εισάγοντας μηδενικά ανάμεσα στα δείγματα των δύο υπο-σημάτων. Στη συνέχεια, τα υπερδειγματοληπτημένα σήματα περνούν από συνέλιξη με τα αντίστοιχα φίλτρα σύνθεσης ($g_0, g_1$). Το τελικό 1Δ σήμα προκύπτει από την πρόσθεση των δύο αυτών κλάδων.
"""

def synthesis1d(g0: np.ndarray, g1: np.ndarray, y0: np.ndarray, y1: np.ndarray) -> np.ndarray:
    """
    Υλοποιεί την 1Δ πολυδιακριτική σύνθεση (Upsampling 2:1 -> Φιλτράρισμα -> Πρόσθεση).
    """
    # 1. Υπερδειγματοληψία 2:1 (Upsampling) των y0 και y1
    # Δημιουργούμε πίνακες με διπλάσιο μήκος γεμάτους μηδενικά
    w0 = np.zeros(2 * len(y0))
    w1 = np.zeros(2 * len(y1))

    # Τοποθετούμε τα δείγματα των y0, y1 στις άρτιες θέσεις
    w0[::2] = y0
    w1[::2] = y1

    # 2. Φιλτράρισμα με τα φίλτρα σύνθεσης (με mode='full' για διατήρηση πληροφορίας)
    r0 = convolve(w0, g0, mode='full')
    r1 = convolve(w1, g1, mode='full')

    # 3. Πρόσθεση των δύο εξόδων για την ανακατασκευή του σήματος
    xhat = r0 + r1

    return xhat

"""### Ανάλυση 2 Διαστάσεων (analysis2d)
Η συνάρτηση `analysis2d` επεκτείνει την πολυδιακριτική ανάλυση σε εικόνες ($2\Delta$ σήματα) εφαρμόζοντας διαχωρίσιμα τα $1\Delta$ φίλτρα.
* **Φάση 1:** Τα φίλτρα μετατρέπονται σε διαστάσεις στήλης $(K, 1)$ και εφαρμόζονται στην εικόνα κατακόρυφα. Ακολουθεί υποδειγματοληψία διαγράφοντας 1 στις 2 γραμμές.
* **Φάση 2:** Τα φίλτρα μετατρέπονται σε διαστάσεις γραμμής $(1, K)$ και εφαρμόζονται στα ενδιάμεσα αποτελέσματα οριζόντια. Ακολουθεί υποδειγματοληψία διαγράφοντας 1 στις 2 στήλες.
Το αποτέλεσμα είναι 4 υπο-μπάντες (y00, y01, y10, y11) που περιέχουν διαφορετικές πληροφορίες συχνοτήτων (π.χ. το y00 έχει τη χαμηλή συχνότητα και είναι μια μικρογραφία της αρχικής εικόνας).
"""

def analysis2d(h0: np.ndarray, h1: np.ndarray, x: np.ndarray) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """
    Υλοποιεί την 2Δ πολυδιακριτική ανάλυση σε δύο φάσεις (στήλες και μετά γραμμές).
    """
    # Μετατροπή 1Δ φίλτρων σε διαστάσεις στήλης (-1, 1) και γραμμής (1, -1)
    h0_col = h0.reshape(-1, 1)
    h1_col = h1.reshape(-1, 1)
    h0_row = h0.reshape(1, -1)
    h1_row = h1.reshape(1, -1)

    # ΦΑΣΗ 1: Εφαρμογή στις Στήλες (Κάθετα)
    # Φιλτράρισμα και υποδειγματοληψία 1:2 κατά τον κατακόρυφο άξονα (κρατάμε άρτιες γραμμές)
    v0_col = convolve2d(x, h0_col, mode='full')
    y0_col = v0_col[::2, :]

    v1_col = convolve2d(x, h1_col, mode='full')
    y1_col = v1_col[::2, :]

    # ΦΑΣΗ 2: Εφαρμογή στις Γραμμές (Οριζόντια)
    # Φιλτράρισμα και υποδειγματοληψία 1:2 κατά τον οριζόντιο άξονα (κρατάμε άρτιες στήλες)
    # Για το ενδιάμεσο y0_col:
    v00 = convolve2d(y0_col, h0_row, mode='full')
    y00 = v00[:, ::2]

    v01 = convolve2d(y0_col, h1_row, mode='full')
    y01 = v01[:, ::2]

    # Για το ενδιάμεσο y1_col:
    v10 = convolve2d(y1_col, h0_row, mode='full')
    y10 = v10[:, ::2]

    v11 = convolve2d(y1_col, h1_row, mode='full')
    y11 = v11[:, ::2]

    return y00, y01, y10, y11

"""### Σύνθεση 2 Διαστάσεων (synthesis2d)
Η συνάρτηση `synthesis2d` πραγματοποιεί την ακριβώς αντίστροφη διαδικασία για να ανακατασκευάσει την αρχική εικόνα από τις 4 υπο-μπάντες.
* **Φάση 1 (Οριζόντια):** Εφαρμόζεται υπερδειγματοληψία 2:1 ανάμεσα στις στήλες (προσθήκη μηδενικών) και έπειτα οριζόντιο φιλτράρισμα με τα $g_0, g_1$ (ως φίλτρα γραμμής) για την ανακατασκευή των ενδιάμεσων κατακόρυφων υπο-σημάτων.
* **Φάση 2 (Κατακόρυφα):** Εφαρμόζεται υπερδειγματοληψία 2:1 ανάμεσα στις γραμμές και έπειτα κατακόρυφο φιλτράρισμα με τα $g_0, g_1$ (ως φίλτρα στήλης). Η πρόσθεση των τελικών αποτελεσμάτων δίνει την ανακατασκευασμένη εικόνα $\hat{x}$.
"""

def synthesis2d(g0: np.ndarray, g1: np.ndarray, y00: np.ndarray, y01: np.ndarray, y10: np.ndarray, y11: np.ndarray) -> np.ndarray:
    """
    Υλοποιεί την 2Δ πολυδιακριτική σύνθεση για την τέλεια ανακατασκευή της εικόνας.
    """
    g0_col = g0.reshape(-1, 1)
    g1_col = g1.reshape(-1, 1)
    g0_row = g0.reshape(1, -1)
    g1_row = g1.reshape(1, -1)

    # Βοηθητική εσωτερική συνάρτηση για τη Φάση 1 (Οριζόντια Σύνθεση)
    def upsample_and_filter_rows(y_0, y_1):
        H, W = y_0.shape
        # Upsampling 2:1 οριζόντια (διπλασιάζουμε τις στήλες βάζοντας μηδενικά)
        w_0 = np.zeros((H, 2 * W))
        w_1 = np.zeros((H, 2 * W))
        w_0[:, ::2] = y_0
        w_1[:, ::2] = y_1

        # Φιλτράρισμα με g0, g1 κατά γραμμές
        r_0 = convolve2d(w_0, g0_row, mode='full')
        r_1 = convolve2d(w_1, g1_row, mode='full')
        return r_0 + r_1

    # ΦΑΣΗ 1: Σύνθεση κατά τις Γραμμές (για τα ζεύγη 00-01 και 10-11)
    y0_col_hat = upsample_and_filter_rows(y00, y01)
    y1_col_hat = upsample_and_filter_rows(y10, y11)

    # Βοηθητική εσωτερική συνάρτηση για τη Φάση 2 (Κατακόρυφη Σύνθεση)
    def upsample_and_filter_cols(y_0, y_1):
        H, W = y_0.shape
        # Upsampling 2:1 κάθετα (διπλασιάζουμε τις γραμμές βάζοντας μηδενικά)
        w_0 = np.zeros((2 * H, W))
        w_1 = np.zeros((2 * H, W))
        w_0[::2, :] = y_0
        w_1[::2, :] = y_1

        # Φιλτράρισμα με g0, g1 κατά στήλες
        r_0 = convolve2d(w_0, g0_col, mode='full')
        r_1 = convolve2d(w_1, g1_col, mode='full')
        return r_0 + r_1

    # ΦΑΣΗ 2: Σύνθεση κατά τις Στήλες
    xhat = upsample_and_filter_cols(y0_col_hat, y1_col_hat)

    return xhat