if __name__ == "__main__":

    # Image Loading and Grayscale Conversion
    # Load the source image and convert it to a 2D float array
    img_path = 'cameraman.png'
    img_pil = Image.open(img_path).convert('L')
    f = np.array(img_pil, dtype=float)
    N1, N2 = f.shape

    # Parameter Initialization
    # Define dynamic cutoff frequencies and directional parameters
    D0_1 = min(N1, N2) / 5
    D0_2 = min(N1, N2) / 2
    D0_dir = min(N1, N2) / 8  # Radial cutoff for directional bank
    q = 8                     # Number of directional sectors
    K = 2                     # Smoothing exponent for angular windowing

    print(f"Dimensions: {N1}x{N2}, D0_1={D0_1:.2f}, D0_2={D0_2:.2f}, D0_dir={D0_dir:.2f}")

    # Ideal Filter Analysis (Low-Pass & High-Pass)
    # Compare sharp frequency truncation across two different cutoff radii
    H_IL1 = designLowFilter(N1, N2, (0, D0_1, None))
    H_IL2 = designLowFilter(N1, N2, (0, D0_2, None))
    g_IL1 = freqFilter(f, H_IL1, N1, N2)
    g_IL2 = freqFilter(f, H_IL2, N1, N2)
    show_results("Ideal Low-Pass Filters", f, g_IL1, "D0 = min/5", g_IL2, "D0 = min/2")

    H_IH1 = designHighFilter(N1, N2, (0, D0_1, None))
    H_IH2 = designHighFilter(N1, N2, (0, D0_2, None))
    g_IH1 = freqFilter(f, H_IH1, N1, N2)
    g_IH2 = freqFilter(f, H_IH2, N1, N2)
    show_results("Ideal High-Pass Filters", f, g_IH1, "D0 = min/5", g_IH2, "D0 = min/2")

    # Gaussian Filter Analysis (Low-Pass & High-Pass)
    # Evaluate smooth frequency transitions to mitigate ringing artifacts
    H_GL1 = designLowFilter(N1, N2, (2, D0_1, None))
    H_GL2 = designLowFilter(N1, N2, (2, D0_2, None))
    g_GL1 = freqFilter(f, H_GL1, N1, N2)
    g_GL2 = freqFilter(f, H_GL2, N1, N2)
    show_results("Gaussian Low-Pass Filters", f, g_GL1, "D0 = min/5", g_GL2, "D0 = min/2")

    H_GH1 = designHighFilter(N1, N2, (2, D0_1, None))
