def show_results(title, original, img1, title1, img2, title2):
    """
    Utility to display a 1x3 subplot grid for comparing
    the original image with two filtered versions.
    """
    plt.figure(figsize=(12, 4))
    plt.suptitle(title, fontsize=14)

    plt.subplot(1, 3, 1)
    plt.imshow(original, cmap='gray')
    plt.title("Original Image")
    plt.axis('off')

    plt.subplot(1, 3, 2)
    plt.imshow(img1, cmap='gray')
    plt.title(title1)
    plt.axis('off')

    plt.subplot(1, 3, 3)
    plt.imshow(img2, cmap='gray')
    plt.title(title2)
    plt.axis('off')

    plt.tight_layout()

def plot_directional_bank(f, H_bank, N1, N2, title):
    """
    Displays the output of a directional filter bank in a 3x3 grid.
    Visualizes H0 (low-pass) and H1...Hq (directional components).
    """
    q = H_bank.shape[2] - 1
    plt.figure(figsize=(10, 10))
    plt.suptitle(title, fontsize=16)

    # Process and display the base Low-Pass component (H0)
    g0 = freqFilter(f, H_bank[:, :, 0], N1, N2)
    plt.subplot(3, 3, 1)
    plt.imshow(g0, cmap='gray')
    plt.title("H0: Low-Pass")
    plt.axis('off')

    # Process and display each directional sector (H1 to Hq)
    for i in range(1, q + 1):
        g_i = freqFilter(f, H_bank[:, :, i], N1, N2)
        plt.subplot(3, 3, i + 1)
        plt.imshow(g_i, cmap='gray')
        plt.title(f"H{i}: Directional")
        plt.axis('off')

    plt.tight_layout()

